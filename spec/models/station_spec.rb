require 'rails_helper'

describe Station do
  describe 'excluded_reason' do
    it 'is valid without a reason' do
      expect(build(:station, excluded_reason: nil)).to be_valid
    end

    it 'accepts every listed reason' do
      described_class::EXCLUDED_REASONS.each_value do |reason|
        expect(build(:station, excluded_reason: reason)).to be_valid
      end
    end

    it 'rejects a reason that is not listed' do
      station = build(:station, excluded_reason: 'mobile')

      expect(station).not_to be_valid
      expect(station.errors[:excluded_reason]).to be_present
    end
  end

  describe 'uuid' do
    # Rails 7.0 returns only the primary key from INSERT, hence the reload.
    it 'is generated by the database, distinct per station' do
      first = create(:station).reload
      second = create(:station).reload

      expect(first.uuid).to be_present
      expect(second.uuid).not_to eq(first.uuid)
    end
  end

  describe '.shown' do
    it 'returns only stations without an excluded reason' do
      shown = create(:station)
      create(:station, excluded_reason: described_class::EXCLUDED_REASONS[:temporary])

      expect(described_class.shown).to contain_exactly(shown)
    end
  end

  describe '#is_active' do
    it 'is false when no stream ever reported' do
      station = create(:station)
      create(:station_stream, station: station, last_measured_at: nil)

      expect(station.is_active).to be(false)
    end

    it 'is true when any stream reported within StationStream::ACTIVE_FOR' do
      station = create(:station)
      stream_configuration = create(:stream_configuration)
      create(:station_stream, station: station, stream_configuration: stream_configuration, last_measured_at: nil)
      create(:station_stream, station: station, stream_configuration: stream_configuration, last_measured_at: 1.hour.ago)

      expect(station.is_active).to be(true)
    end
  end
end
